#!/usr/bin/env python3
"""Writes the ladder card's frames (rig.py builds them) for the plugin.

    python3 docs/preview/lode/build-lode.py                → plugins/usage-meter/hooks/lode-data.js, lode-fine-data.js (3x, for the cell font)
    python3 docs/preview/lode/build-lode.py --sheet x.png  (also a picture of every frame)
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rig  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
OUT = os.path.join(ROOT, 'plugins', 'usage-meter', 'hooks', 'lode-data.js')
FINE_OUT = os.path.join(ROOT, 'plugins', 'usage-meter', 'hooks', 'lode-fine-data.js')

if __name__ == '__main__':
    data = rig.frames()
    muzzle = data.pop('muzzle')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by docs/preview/lode/build-lode.py; do not edit by hand.\nexport default ')
        json.dump({'keys': rig.KEYS, 'size': [rig.W, rig.H], 'frames': data, 'muzzle': {'runner': muzzle}}, f, separators=(',', ':'))
        f.write(';\n')
    # the cell font's frames: the same poses drawn three times finer, each row run-length coded ('12.3U' = 12 empty, 3 U)
    rig.set_scale(3)
    fine = rig.frames()
    fmuzzle = [[x * 3 + 1, y * 3 + 1] for x, y in fine.pop('muzzle')]
    rle = lambda row: ''.join(f'{len(m.group(0))}{m.group(1)}' for m in re.finditer(r'(.)\1*', row))
    with open(FINE_OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by docs/preview/lode/build-lode.py; do not edit by hand.\nexport default ')
        json.dump({'size': [rig.W * 3, rig.H * 3], 'frames': {h: {k: [[rle(r) for r in fr] for fr in v] for k, v in fine[h].items()} for h in fine},
                   'muzzle': {'runner': fmuzzle}}, f, separators=(',', ':'))
        f.write(';\n')
    rig.set_scale(1)
    if '--sheet' in sys.argv:
        rig.sheet(sys.argv[sys.argv.index('--sheet') + 1], rig.frames())
    print('wrote', OUT, {h: {k: len(v) for k, v in data[h].items()} for h in data})
