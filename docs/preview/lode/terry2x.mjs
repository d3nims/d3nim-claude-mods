// Terry at twice the dots, for the cell font: every frame of the card (terrier-data.js) through Scale2x is the
// starting point, and the frames touched up by hand in the 2x dot editor replace it.
//   node docs/preview/lode/terry2x.mjs editor   → docs/preview/terry2x-editor-data.json (the editor page's data)
//   node docs/preview/lode/terry2x.mjs card     → plugins/usage-meter/hooks/terry-2x-data.js (from terry-edits-2x.json)
// The editor's saved frames come in as for the 1x editor: ArtifactData list of `edits2x` with out_dir, then
//   node docs/preview/lode/terry2x.mjs import <folder>   → docs/preview/terry-edits-2x.json
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import SPRITE from '../../../plugins/usage-meter/hooks/terrier-data.js'

const HERE = dirname(fileURLToPath(import.meta.url))
const PREVIEW = join(HERE, '..')
const EDITS = join(PREVIEW, 'terry-edits-2x.json')

// Scale2x on rows of keys ('.' empty), the same rule as terry-fine.js
export function scale2xRows(rows) {
  const h = rows.length, w = rows[0].length
  const at = (x, y) => rows[Math.min(h - 1, Math.max(0, y))][Math.min(w - 1, Math.max(0, x))]
  const out = Array.from({ length: h * 2 }, () => [])
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const E = at(x, y), B = at(x, y - 1), D = at(x - 1, y), F = at(x + 1, y), H = at(x, y + 1)
    let e0 = E, e1 = E, e2 = E, e3 = E
    if (B !== H && D !== F) {
      if (D === B) e0 = D
      if (B === F) e1 = F
      if (D === H) e2 = D
      if (H === F) e3 = F
    }
    out[y * 2].push(e0, e1); out[y * 2 + 1].push(e2, e3)
  }
  return out.map(r => r.join(''))
}

// the paint palette, by what each colour is on him (1-9 pick the first nine)
// (a list, not an object: an object would put the all-digit hex keys first)
const NAMES = [
  ['f2f2f2', '흰 털'], ['d8d8d8', '밝은 털'], ['b0b0b0', '연한 회색'], ['777777', '보통 회색'], ['515151', '귀·짙은 회색'],
  ['3a3a3a', '테두리'], ['181818', '눈'], ['141414', '코'], ['ec7080', '혀'], ['d1d1d1', '밝은 털 2'], ['707070', '회색 2'],
  ['6d6d6d', '회색 3'], ['6b6b6b', '회색 4'], ['5e5e5e', '어두운 회색'], ['464646', '짙은 회색 2'], ['3f3f3f', '테두리 2'],
  ['2c2c2c', '눈꺼풀·짙은 선'], ['e29ca8', '귀 안쪽'], ['702432', '입 안'], ['c44e62', '혀 그림자'],
]
const keyOf = hex => SPRITE.alphabet[SPRITE.palette.indexOf(hex)]

const cmd = process.argv[1] === fileURLToPath(import.meta.url) ? process.argv[2] : null // (imported: no command)
if (cmd === 'editor') {
  const sets = {}
  for (const [name, set] of Object.entries(SPRITE.sets)) sets[name] = { durations: set.durations, frames: set.frames.map(scale2xRows) }
  const keys = Object.fromEntries(SPRITE.palette.map((hex, i) => [SPRITE.alphabet[i], hex]))
  const palette = NAMES.filter(([h]) => SPRITE.palette.includes(h)).map(([h, name]) => [keyOf(h), name])
  const first = sets.sit.frames[0]
  let ground = 0
  for (const set of Object.values(sets)) for (const f of set.frames) f.forEach((r, y) => { if (/[^.]/.test(r)) ground = Math.max(ground, y) })
  const data = { width: first[0].length, height: first.length, ground, keys, palette, features: ['181818', '141414', '2c2c2c'].map(keyOf), sets }
  writeFileSync(join(PREVIEW, 'terry2x-editor-data.json'), JSON.stringify(data))
  console.log('editor data', data.width + 'x' + data.height, 'ground', ground, Object.keys(sets).length, 'sets')
} else if (cmd === 'card') {
  const edits = existsSync(EDITS) ? JSON.parse(readFileSync(EDITS, 'utf8')) : {}
  let n = 0
  for (const frames of Object.values(edits)) n += Object.keys(frames).length
  writeFileSync(join(HERE, '../../../plugins/usage-meter/hooks/terry-2x-data.js'),
    '// Generated by docs/preview/lode/terry2x.mjs from docs/preview/terry-edits-2x.json; do not edit by hand.\n' +
    '// Terry\'s frames touched up at twice the dots (set -> frame -> rows in terrier-data.js\'s keys).\nexport default ' + JSON.stringify(edits) + ';\n')
  console.log(n, 'frames at 2x')
} else if (cmd === 'import') {
  const out = existsSync(EDITS) ? JSON.parse(readFileSync(EDITS, 'utf8')) : {}
  const allowed = new Set(['.', ...SPRITE.alphabet.slice(0, SPRITE.palette.length)])
  const walk = d => readdirSync(d).flatMap(f => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]))
  let n = 0
  for (const path of walk(process.argv[3]).filter(p => p.endsWith('.json'))) {
    const doc = JSON.parse(readFileSync(path, 'utf8'))
    const { set, frame, rows } = doc.data || doc
    if (typeof set !== 'string' || !Number.isInteger(frame) || !Array.isArray(rows)) { console.log('skipped', path); continue }
    ;(out[set] ||= {})[frame] = rows.map(r => [...String(r)].map(c => (allowed.has(c) ? c : '.')).join(''))
    n++
  }
  writeFileSync(EDITS, JSON.stringify(out, null, 1))
  console.log(n, 'frames ->', EDITS)
} else if (cmd !== null) {
  console.log('usage: node docs/preview/lode/terry2x.mjs editor | card | import <folder>')
}
