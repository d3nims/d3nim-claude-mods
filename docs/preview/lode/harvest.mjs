// Gathers every cell the ladder card's fine scene (plugins/usage-meter/hooks/lode-fine.js) draws, for the Lode Cells
// font: the whole route at a step of about a pixel, and every resting mood through its loop, for both heroes.
//   node docs/preview/lode/harvest.mjs           → plugins/usage-meter/hooks/lode-glyphs.js, docs/preview/lode/glyphs.json
// Then build the font: <python with fontTools> docs/preview/lode/cellfont.py --glyphs docs/preview/lode/glyphs.json ...
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { fineScene, cellsOf, keyOf, packKeys } from '../../../plugins/usage-meter/hooks/lode-fine.js'
import { onRouteOf } from '../../../plugins/usage-meter/hooks/lode.js'
import { TERRY_ROWS } from '../../../plugins/usage-meter/hooks/render.js'

const HERE = dirname(fileURLToPath(import.meta.url))
const COLUMNS = 84 // wider than any card: every cell he can have ahead of and behind him
const seen = new Map()
const take = (hero, mood, ms, effort = 'high') => {
  const cells = cellsOf(fineScene(hero, mood, ms, COLUMNS, effort), COLUMNS, TERRY_ROWS)
  for (const c of cells) if (c) { const k = keyOf(c.mask, c.over); seen.set(k, (seen.get(k) || 0) + 1) }
}
const route = onRouteOf(3, 128)
const t0 = Date.now()
for (const hero of ['runner', 'monk']) {
  // the route is the same at every pace: walked in steps fine enough to land on every pixel (a climb rises more than
  // a pixel a frame), then once more at the fastest pace for the speed lines behind him
  for (let ms = 0; ms < route.roundSecs * 1000 + 2000; ms += 1000 / 240) take(hero, 'run', ms)
  const fast = route.PACE.max
  for (let ms = 0; ms < (route.roundSecs * 1000 + 2000) / fast; ms += 1000 / 60 / fast) take(hero, 'run', ms, 'max')
  for (const [mood, secs] of [['sit', 6.1], ['wag', 1], ['ask', 2.5], ['happy', 0.6], ['sleep', 2.5], ['sad', 0.6], ['dig', 2.5]])
    for (let ms = 0; ms < secs * 1000; ms += 1000 / 30) take(hero, mood, ms)
}
// the full cell and the empty-lit one are always there; then the most used first
const keys = [...seen.entries()].sort((a, b) => b[1] - a[1]).map(([k]) => k)
writeFileSync(join(HERE, '../../../plugins/usage-meter/hooks/lode-glyphs.js'),
  '// Generated by docs/preview/lode/harvest.mjs; do not edit by hand. Glyph i of the Lode Cells font is U+100000 + i.\nexport default ' + JSON.stringify(packKeys(keys)) + ';\n')
writeFileSync(join(HERE, 'glyphs.json'), JSON.stringify(keys))
console.log(keys.length, 'glyphs from', [...seen.values()].reduce((a, b) => a + b, 0), 'cells in', ((Date.now() - t0) / 1000).toFixed(1) + 's', 'round', route.roundSecs.toFixed(1) + 's')
