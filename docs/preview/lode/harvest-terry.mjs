// Gathers every cell Terry's fine card (plugins/usage-meter/hooks/terry-fine.js) draws, for the Lode Cells font: every
// mood through its loops (each run style too), then the sky through a whole day.
//   node docs/preview/lode/harvest-terry.mjs   → plugins/usage-meter/hooks/terry-glyphs.js, docs/preview/lode/terry-glyphs.json
// Then build the font with both lists (cellfont.py --glyphs glyphs.json out.ttf version --more terry-glyphs.json 10a000).
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { terryFineScene } from '../../../plugins/usage-meter/hooks/terry-fine.js'
import { cellsOf, keyOf, packKeys } from '../../../plugins/usage-meter/hooks/lode-fine.js'
import { TERRY_ROWS, TERRY_COLS } from '../../../plugins/usage-meter/hooks/render.js'

const HERE = dirname(fileURLToPath(import.meta.url))
const seen = new Map()
const take = (mood, ms, hour, columns, effort = 'high', date = null) => {
  for (const c of cellsOf(terryFineScene(mood, ms, hour, columns, effort, date), columns, TERRY_ROWS))
    if (c) { const k = keyOf(c.mask, c.over); seen.set(k, (seen.get(k) || 0) + 1) }
}
const t0 = Date.now()
const MOODS = ['sit', 'wag', 'bark', 'happy', 'sleep', 'sniff', 'dig', 'fetch', 'ask', 'sad', 'door', 'catch', 'droop',
  'stretch', 'eat', 'pet']
// 13 s holds every loop (the slowest, the blink, comes every 4.2 s) and is not a whole number of any of them
for (const mood of MOODS) for (let ms = 0; ms < 13000; ms += 1000 / 30) take(mood, ms, 13, TERRY_COLS)
// running, the ground slides past with its pebbles and tufts at random: a long run gathers most of what it can show
for (const effort of ['low', 'medium', 'high', 'xhigh', 'max']) for (let ms = 0; ms < 90000; ms += 1000 / 30) take('run', ms, 13, TERRY_COLS, effort)
// the sun, the moon and the stars across the day, at the full width and a narrow one
for (const columns of [TERRY_COLS, 30]) for (let hour = 0; hour < 24; hour += 0.1) for (const ms of [0, 400, 800, 1200]) take('sit', ms, hour, columns)
// Chuseok's full moon, through the night
for (let hour = 18; hour < 30; hour += 0.1) take('sit', 0, hour % 24, TERRY_COLS, 'high', { holiday: 'chuseok' })
const keys = [...seen.entries()].sort((a, b) => b[1] - a[1]).map(([k]) => k)
writeFileSync(join(HERE, '../../../plugins/usage-meter/hooks/terry-glyphs.js'),
  '// Generated by docs/preview/lode/harvest-terry.mjs; do not edit by hand. Glyph i is U+10A000 + i of the Lode Cells font.\nexport default ' + JSON.stringify(packKeys(keys)) + ';\n')
writeFileSync(join(HERE, 'terry-glyphs.json'), JSON.stringify(keys))
console.log(keys.length, 'glyphs from', [...seen.values()].reduce((a, b) => a + b, 0), 'cells in', ((Date.now() - t0) / 1000).toFixed(1) + 's')
